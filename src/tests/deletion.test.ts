import {test} from "node:test";
import assert from "node:assert/strict";
import {mkdtempSync} from "node:fs";
import {tmpdir} from "node:os";
import path from "node:path";
import {POST} from "../app/api/hub/route.ts";
import {store,demoSession} from "../lib/hub-store.ts";
import {demoAccounts} from "../lib/hub-demo.ts";
import {blankProject} from "../lib/hub-types.ts";

test("only listing owners can confirm deletion; all dependent records disappear and repo can be republished",async t=>{
 process.env.YAKKEEPER_LOCAL_DEMO="true";
 process.env.YAKKEEPER_LOCAL_DB=path.join(mkdtempSync(path.join(tmpdir(),"yk-delete-")),"db.sqlite");
 t.mock.method(globalThis,"fetch",async()=>{throw Error("Deletion must not call GitHub or notifications");});
 const cookies=await Promise.all(demoAccounts.map(async a=>"yk_demo="+await demoSession(a.id)));
 const call=async(body:unknown,cookie="",origin="http://127.0.0.1:3000")=>POST(new Request("http://127.0.0.1:3000/api/hub",{method:"POST",headers:{host:"127.0.0.1:3000",origin,cookie},body:JSON.stringify(body)}));
 const project={...blankProject,repo_id:900000003};
 assert.equal((await call({action:"saveProject",project},cookies[2])).status,200);
 const db=store(true), saved=(await db.find("yak_projects"))[0],id=String(saved.id);
 const {id:oldId,...otherFields}=saved;
 const other=await db.save("yak_projects",{...otherFields,repo_id:900000004,owner_id:demoAccounts[3].id});
 assert.ok(other);
 await db.save("yak_banners",{id:"fixture/banner.webp",data:"fixture"});
 await db.patch("yak_projects",id,{banner_path:"fixture/banner.webp"});
 for(let i=0;i<105;i++) await db.save("yak_interactions",{project_id:id,kind:"idea",owner_id:demoAccounts[2].id,applicant_id:demoAccounts[1].id,message:"A useful idea for improving this project."});
 await db.save("yak_reports",{project_id:id,reason:"A disposable report for deletion testing."});
 const retained=await db.save("yak_interactions",{project_id:other.id,kind:"idea"});
 const body={action:"deleteProject",id,confirm:true};
 assert.equal((await call(body)).status,401);
 for(const cookie of [cookies[0],cookies[1],cookies[3]]) assert.equal((await call(body,cookie)).status,403);
 assert.equal((await call(body,cookies[2],"https://bad.example")).status,403);
 assert.equal((await call({...body,confirm:false},cookies[2])).status,400);
 assert.equal((await db.find("yak_interactions",{project_id:id},200)).length,105);
 assert.equal((await call(body,cookies[2])).status,200);
 assert.equal((await db.find("yak_projects",{id})).length,0);
 assert.equal((await db.find("yak_interactions",{project_id:id})).length,0);
 assert.equal((await db.find("yak_reports",{project_id:id})).length,0);
 assert.equal((await db.find("yak_banners",{id:"fixture/banner.webp"})).length,0);
 assert.equal((await db.find("yak_interactions",{id:retained.id})).length,1);
 assert.equal((await call(body,cookies[2])).status,403);
 assert.equal((await call({action:"saveProject",project},cookies[2])).status,200);
 const restored=(await db.find("yak_projects",{repo_id:project.repo_id}))[0];
 await db.patch("yak_projects",String(restored.id),{moderated:true,visibility:"archived"});
 assert.equal((await call({...body,id:restored.id},cookies[2])).status,200);
 assert.equal((await call({action:"saveProject",project},cookies[2])).status,403);
 assert.equal((await db.find("yak_repo_restrictions",{repo_id:project.repo_id})).length,1);
});
