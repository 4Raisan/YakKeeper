// Run with playwright-cli run-code --filename=scripts/check-collaboration.pw.js
// Requires an isolated local-demo server on 127.0.0.1:3109. Never targets production.
async (page) => {
  const base = "http://127.0.0.1:3109";
  if (new URL(page.url()).origin !== base) throw Error("Open the isolated localhost sandbox first.");
  const check = (value,message) => { if (!value) throw Error(message); };
  const suffix=Date.now().toString();
  const originalTitle="Write the first draft " + suffix;
  const correctedTitle="Write the corrected draft " + suffix;
  const errors=[];
  const watch=p=>p.on("pageerror",e=>errors.push(e.message));
  watch(page);
  const post=(context,data)=>context.request.post(base+"/api/hub",{data,headers:{origin:base}});
  const owner=page.context();
  check((await post(owner,{action:"demoSeed"})).ok(),"Seed failed");
  check((await post(owner,{action:"demoLogin",user_id:"11111111-1111-4111-8111-111111111111"})).ok(),"Owner fixture login failed");
  await page.goto(base+"/?view=my");
  const card=page.getByRole("article").filter({has:page.getByRole("button",{name:"yakkeeper-sandbox",exact:true})});
  await card.getByRole("button",{name:"Edit project",exact:true}).click();
  let dialog=page.getByRole("dialog");
  await dialog.getByLabel("How people join").selectOption("invite_only");
  await dialog.getByLabel("Starter task",{exact:true}).fill("Check the mobile sign-in screen");
  await dialog.getByLabel("Starter task effort (optional)").fill("30 minutes · beginner friendly");
  await dialog.getByRole("button",{name:"Save changes",exact:true}).click();
  await dialog.waitFor({state:"hidden"});
  await card.getByRole("button",{name:"Members",exact:true}).click();
  dialog=page.getByRole("dialog");
  await dialog.getByLabel("GitHub username").fill("asha-demo");
  await dialog.getByRole("button",{name:"Look up account"}).click();
  await dialog.getByRole("button",{name:"Send invitation"}).click();
  await dialog.getByText("Invitation pending",{exact:true}).waitFor();
  await page.screenshot({path:"output/playwright/members-invitation.png"});
  const state=await (await owner.request.get(base+"/api/hub")).json();
  const project=state.projects.find(p=>p.title==="yakkeeper-sandbox");
  check(project.join_policy==="invite_only","Join policy not saved");
  const browser=owner.browser();
  check(browser,"Browser does not support isolated contexts");
  const member=await browser.newContext();
  const memberPage=await member.newPage();watch(memberPage);
  await post(member,{action:"demoLogin",user_id:"22222222-2222-4222-8222-222222222222"});
  check((await member.request.get(base+"/api/hub?resource=board&project_id="+project.id)).status()===403,"Pending invite granted board access");
  await memberPage.goto(base+"/?view=my");
  await memberPage.getByRole("button",{name:"Accept invitation",exact:true}).click();
  const memberCard=memberPage.getByRole("article").filter({has:memberPage.getByRole("button",{name:"yakkeeper-sandbox",exact:true})});
  await memberCard.getByRole("button",{name:"Task board",exact:true}).click();
  await memberPage.getByRole("button",{name:"Add task",exact:true}).click();
  await memberPage.getByLabel("Task title",{exact:true}).fill(originalTitle);
  await memberPage.getByRole("button",{name:"Create task",exact:true}).click();
  let task=memberPage.getByRole("article").filter({has:memberPage.getByRole("heading",{name:originalTitle,exact:true})});
  await task.getByRole("button",{name:"I’m working on this",exact:true}).click();
  await task.getByRole("button",{name:"Edit task",exact:true}).click();
  await memberPage.getByLabel("Task title",{exact:true}).fill(correctedTitle);
  await memberPage.getByRole("button",{name:"Save task",exact:true}).click();
  await memberPage.getByRole("heading",{name:correctedTitle,exact:true}).waitFor();
  await page.getByRole("button",{name:"Close dialog"}).click();
  await card.getByRole("button",{name:"Task board",exact:true}).click();
  task=page.getByRole("article").filter({has:page.getByRole("heading",{name:correctedTitle,exact:true})});
  await task.getByRole("button",{name:"Archive task",exact:true}).click();
  await page.getByRole("button",{name:"Archived",exact:true}).click();
  task=page.getByRole("article").filter({has:page.getByRole("heading",{name:correctedTitle,exact:true})});
  await task.getByText("@asha-demo",{exact:true}).waitFor();
  await page.screenshot({path:"output/playwright/task-archive.png"});
  await task.getByRole("button",{name:"Restore task",exact:true}).click();
  await page.getByRole("button",{name:"Active tasks",exact:true}).click();
  task=page.getByRole("article").filter({has:page.getByRole("heading",{name:correctedTitle,exact:true})});
  await task.getByText("@asha-demo",{exact:true}).waitFor();
  const anonymous=await browser.newContext({viewport:{width:390,height:844}});
  const publicPage=await anonymous.newPage();watch(publicPage);
  await publicPage.goto(base+"/projects/"+project.id);
  await publicPage.getByText("Check the mobile sign-in screen",{exact:true}).waitFor();
  check(await publicPage.getByRole("button",{name:"Invite only",exact:true}).isDisabled(),"Public invite-only admission is not disabled");
  check(await publicPage.getByRole("button",{name:"Task board",exact:true}).count()===0,"Anonymous visitor sees team controls");
  check(await publicPage.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),"Mobile page overflows horizontally");
  await publicPage.screenshot({path:"output/playwright/project-share-mobile.png",fullPage:true});
  await page.getByRole("button",{name:"Close dialog"}).click();
  await card.getByRole("button",{name:"Members",exact:true}).click();
  await page.getByRole("button",{name:"Remove member",exact:true}).click();
  check((await member.request.get(base+"/api/hub?resource=board&project_id="+project.id)).status()===403,"Removed member still has access");
  await memberPage.getByRole("button",{name:"Refresh tasks",exact:true}).click();
  await memberPage.getByRole("alert").filter({hasText:"Only the owner"}).waitFor();
  check(errors.length===0,"Browser errors: "+errors.join("; "));
  await member.close();await anonymous.close();
  return {passed:true,checks:["owner invitation","recipient acceptance","member task edit","owner archive/restore","retained participant","public share page","mobile layout","removal revocation"],browserErrors:errors};
}
