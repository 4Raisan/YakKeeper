// Local-demo UI check. Repository URLs are display fixtures; links are never opened.
async (page) => {
  const base="http://127.0.0.1:3109";
  if(new URL(page.url()).origin!==base)throw Error("Local sandbox only");
  const check=(value,message)=>{if(!value)throw Error(message);};
  const owner=page.context();
  const post=(ctx,data)=>ctx.request.post(base+"/api/hub",{data,headers:{origin:base}});
  await post(owner,{action:"demoSeed"});
  await post(owner,{action:"demoLogin",user_id:"11111111-1111-4111-8111-111111111111"});
  const state=await (await owner.request.get(base+"/api/hub")).json();
  const request=state.inbox.find(r=>r.applicant_id==="22222222-2222-4222-8222-222222222222");
  await post(owner,{action:"status",id:request.id,status:"Accepted"});
  const project=state.projects.find(p=>p.id===request.project_id);
  const fixture=async route=>{
    const response=await route.fetch();const data=await response.json();
    for(const project of data.projects || [])project.repo="https://github.com/4Raisan/YakKeeper";
    await route.fulfill({response,json:data});
  };
  await page.route("**/api/hub?page=*",fixture);
  await page.goto(base+"/?view=applications");
  const findCard=p=>p.getByRole("article").filter({has:p.getByText("@asha-demo",{exact:true})}).filter({has:p.locator('a.application-project[href="/projects/'+project.id+'"]')});
  let card=findCard(page);
  await card.getByRole("button",{name:"Task board",exact:true}).waitFor();
  check(await card.getByRole("link",{name:"Repository",exact:true}).isVisible(),"Repository hidden behind secondary controls");
  check(await card.getByRole("combobox",{name:"Status for asha-demo",exact:true}).inputValue()==="Accepted","Owner cannot review status");
  check(!(await card.innerText()).includes("permissions are managed separately"),"Disclaimer still present");
  check(await card.getByText(request.message,{exact:true}).count()===1,"Message repeated");
  check(await card.locator("time").evaluate(el=>parseFloat(getComputedStyle(el).fontSize))>=14,"Date remains too small");
  const main=await card.locator(".application-main").boundingBox();
  const actions=await card.locator(".application-actions").boundingBox();
  check(actions.x>main.x+main.width,"Actions are not on the right");
  check((await card.boundingBox()).height<260,"Short card is still unnecessarily tall");
  if(await page.getByRole("button",{name:"Switch to dark theme",exact:true}).count())await page.getByRole("button",{name:"Switch to dark theme",exact:true}).click();
  await page.screenshot({path:"output/playwright/applications-owner-desktop.png"});
  const member=await owner.browser().newContext({viewport:{width:390,height:844}});
  await post(member,{action:"demoLogin",user_id:"22222222-2222-4222-8222-222222222222"});
  const memberPage=await member.newPage();
  await memberPage.route("**/api/hub?page=*",fixture);
  await memberPage.goto(base+"/?view=applications");
  await memberPage.getByRole("button",{name:/^Sent /}).click();
  card=findCard(memberPage);
  await card.getByText("Accepted",{exact:true}).waitFor();
  check(await card.getByRole("combobox").count()===0,"Applicant sees owner review controls");
  check(await card.getByRole("button",{name:"Task board",exact:true}).isVisible(),"Mobile task board action missing");
  check(await card.getByRole("link",{name:"Repository",exact:true}).isVisible(),"Mobile repository action missing");
  check(await memberPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Mobile layout overflows");
  await memberPage.screenshot({path:"output/playwright/applications-sent-mobile.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Owner mobile layout overflows");
  await page.screenshot({path:"output/playwright/applications-owner-mobile.png",fullPage:true});
  await page.getByRole("button",{name:"Explore",exact:true}).click();
  const search=page.getByRole("textbox",{name:"Search projects",exact:true});
  await search.click();
  check(await search.evaluate(el=>getComputedStyle(el).outlineStyle)==="none","Search still has an inner focus outline");
  check(await page.locator(".board-toolbar .search").evaluate(el=>getComputedStyle(el).boxShadow)==="none","Search still glows");
  await page.keyboard.press("Tab");
  const filter=page.getByRole("combobox",{name:"Filter projects",exact:true});
  check(await filter.evaluate(el=>el===document.activeElement),"Keyboard does not reach filter");
  check(await filter.evaluate(el=>getComputedStyle(el).outlineStyle)==="none","Filter has a second inner outline");
  check(await page.locator(".board-toolbar .filter").evaluate(el=>getComputedStyle(el).outlineStyle)!=="none","Keyboard focus indicator is missing");
  await page.screenshot({path:"output/playwright/search-focus-mobile.png"});
  await member.close();
  return {passed:true,checks:["owner review controls","applicant status","username and project","right-side actions","visible mobile links","compact height","readable date","no focus glow","single keyboard focus indicator","390px overflow"]};
}
