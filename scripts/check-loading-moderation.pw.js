// Requires the isolated localhost demo server used by check-collaboration.pw.js.
async (page) => {
  const base="http://127.0.0.1:3109";
  if(new URL(page.url()).origin!==base) throw Error("Local sandbox only");
  const check=(value,message)=>{if(!value)throw Error(message);};
  const owner=page.context();
  const post=(context,data)=>context.request.post(base+"/api/hub",{data,headers:{origin:base}});
  await post(owner,{action:"demoSeed"});
  await post(owner,{action:"demoLogin",user_id:"11111111-1111-4111-8111-111111111111"});
  // Hold the initial read open: the loading state must be visible before data arrives.
  let releaseProjects;
  const projectGate=new Promise(resolve=>{releaseProjects=resolve;});
  const projectsRoute=async route=>{if(route.request().method()==="GET")await projectGate;await route.continue();};
  await page.route("**/api/hub?page=*",projectsRoute);
  await page.goto(base+"/?view=my");
  await page.getByRole("status").filter({hasText:"Loading projects"}).waitFor();
  check(await page.locator(".loading-spinner").first().evaluate(el=>getComputedStyle(el).animationName)!=="none","Loading spinner is not animated");
  await page.emulateMedia({reducedMotion:"reduce"});
  check(await page.locator(".loading-spinner").first().evaluate(el=>getComputedStyle(el).animationName)==="none","Reduced motion is ignored");
  await page.emulateMedia({reducedMotion:"no-preference"});
  releaseProjects();
  const card=page.getByRole("article").filter({has:page.getByRole("button",{name:"yakkeeper-sandbox",exact:true})});
  await card.getByRole("button",{name:"Members",exact:true}).waitFor();
  await page.unroute("**/api/hub?page=*",projectsRoute);
  let releaseMembers;
  const membersGate=new Promise(resolve=>{releaseMembers=resolve;});
  const membersRoute=async route=>{await membersGate;await route.continue();};
  await page.route("**/api/hub?resource=members*",membersRoute);
  await card.getByRole("button",{name:"Members",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Loading members"}).waitFor();
  check(await page.getByText("No members or pending invitations yet.",{exact:true}).count()===0,"Empty members message flashes while loading");
  releaseMembers();
  await page.getByRole("button",{name:"Look up account",exact:true}).waitFor();
  await page.unroute("**/api/hub?resource=members*",membersRoute);
  await page.getByRole("button",{name:"Close dialog"}).click();
  let releaseTasks;
  const taskGate=new Promise(resolve=>{releaseTasks=resolve;});
  const tasksRoute=async route=>{await taskGate;await route.continue();};
  await page.route("**/api/hub?resource=board*",tasksRoute);
  await card.getByRole("button",{name:"Task board",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Loading tasks"}).waitFor();
  await page.screenshot({path:"output/playwright/task-loading.png"});
  releaseTasks();
  await page.getByRole("heading",{name:"Future 0",exact:true}).waitFor();
  await page.unroute("**/api/hub?resource=board*",tasksRoute);
  await page.getByRole("button",{name:"Add task",exact:true}).click();
  await page.getByLabel("Task title",{exact:true}).fill("Delayed task save");
  let releaseSave;
  const saveGate=new Promise(resolve=>{releaseSave=resolve;});
  const saveRoute=async route=>{if(route.request().method()==="POST")await saveGate;await route.continue();};
  await page.route("**/api/hub",saveRoute);
  await page.getByRole("button",{name:"Create task",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Saving task changes"}).waitFor();
  releaseSave();
  await page.getByRole("heading",{name:"Delayed task save",exact:true}).waitFor();
  await page.unroute("**/api/hub",saveRoute);
  await page.getByRole("button",{name:"Close dialog"}).click();
  const browser=owner.browser();
  const member=await browser.newContext({viewport:{width:390,height:844}});
  await post(member,{action:"demoLogin",user_id:"33333333-3333-4333-8333-333333333333"});
  const memberPage=await member.newPage();
  await memberPage.goto(base+"/?view=moderation");
  await memberPage.getByRole("heading",{name:"Owner/admin access only",exact:true}).waitFor();
  check(await memberPage.getByRole("button",{name:"Reports",exact:true}).count()===0,"Reports tab leaked to regular user");
  check(await memberPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Mobile moderation guard overflows");
  const state=await (await owner.request.get(base+"/api/hub")).json();
  const project=state.projects.find(p=>p.title==="yakkeeper-sandbox");
  const result=await post(member,{action:"report",project_id:project.id,reason:"Local test of the project report workflow."});
  check(result.ok(),"Report submission failed");
  await page.goto(base+"/?view=moderation");
  await page.getByText("Local test of the project report workflow.",{exact:true}).waitFor();
  const report=page.getByRole("article").filter({hasText:"Local test of the project report workflow."});
  await report.getByRole("button",{name:"Dismiss",exact:true}).click();
  await report.getByText("Dismissed",{exact:true}).waitFor();
  await page.screenshot({path:"output/playwright/reports-reviewed.png"});
  await member.close();
  return {passed:true,checks:["animated initial loading","reduced motion","member loading without false empty state","task loading","pending task save","admin reports review","regular-user reports denial","390px layout"]};
}
